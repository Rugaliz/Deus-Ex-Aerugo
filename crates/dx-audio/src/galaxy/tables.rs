/// Pitch fraction table (0x1063df80): `trunc(32768 * 2^(-i/768))`.
pub fn pitch_table() -> &'static [i32; 768] {
    static T: OnceLock<[i32; 768]> = OnceLock::new();
    T.get_or_init(|| {
        let mut t = [0i32; 768];
        for (i, v) in t.iter_mut().enumerate() {
            *v = (32768.0 * 2f64.powf(-(i as f64) / 768.0)) as i32;
        }
        t
    })
}

/// Pan law (0x10698390, built at library init on the x87 in double precision): `trunc(32767 * sqrt(i * c))` with
/// `c` the double nearest 1/32767.
pub fn pan_table() -> &'static [i32; 32768] {
    static T: OnceLock<Box<[i32; 32768]>> = OnceLock::new();
    T.get_or_init(|| {
        let mut t = Box::new([0i32; 32768]);
        let c = 1.0f64 / 32767.0;
        for (i, v) in t.iter_mut().enumerate() {
            *v = (((i as f64) * c).sqrt() * 32767.0) as i32;
        }
        t
    })
}

